/** "เขตคลองเตย กรุงเทพมหานคร" or "อำเภอถลาง" → "Khlong Toei, Bangkok" / "Thalang"; the Thai part when unknown. */
function place(t, text) {
  const s = text.trim();
  const whole = t.known(s);
  if (whole) return whole;
  const i = s.lastIndexOf(' ');
  if (i > 0) {
    const a = t.known(s.slice(0, i)), b = t.known(s.slice(i + 1));
    if (a && b) return `${a}, ${b}`;
  }
  return t.name(s);
}
